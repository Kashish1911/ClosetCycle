CREATE TABLE user_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(80) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE,
    area VARCHAR(100) NOT NULL,
    credit_balance INTEGER NOT NULL DEFAULT 200,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'MEMBER',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE clothing_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    description VARCHAR(1200),
    category VARCHAR(40) NOT NULL,
    size VARCHAR(30) NOT NULL,
    condition_label VARCHAR(30) NOT NULL,
    color VARCHAR(40),
    brand VARCHAR(80),
    credit_value INTEGER NOT NULL CHECK (credit_value > 0),
    image_url VARCHAR(300),
    status VARCHAR(20) NOT NULL,
    owner_id BIGINT NOT NULL REFERENCES user_accounts(id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_clothing_status ON clothing_items(status);
CREATE INDEX idx_clothing_owner ON clothing_items(owner_id);

CREATE TABLE exchange_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL REFERENCES user_accounts(id),
    owner_id BIGINT NOT NULL REFERENCES user_accounts(id),
    requested_item_id BIGINT NOT NULL REFERENCES clothing_items(id),
    offered_item_id BIGINT REFERENCES clothing_items(id),
    type VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    credit_difference INTEGER NOT NULL,
    requester_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    owner_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_exchange_requester ON exchange_requests(requester_id);
CREATE INDEX idx_exchange_owner ON exchange_requests(owner_id);
CREATE INDEX idx_exchange_status ON exchange_requests(status);

CREATE TABLE credit_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES user_accounts(id),
    exchange_request_id BIGINT REFERENCES exchange_requests(id),
    amount INTEGER NOT NULL,
    description VARCHAR(180) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_credit_user_created ON credit_transactions(user_id, created_at);
